create or replace function public.claim_first_admin()
returns boolean language plpgsql security definer set search_path = public, private, pg_temp as $$
begin
  if auth.uid() is null then return false; end if;
  if not exists(select 1 from public.user_roles) then
    insert into public.user_roles(user_id, role) values (auth.uid(), 'admin') on conflict do nothing;
    insert into public.audit_logs(actor_id, event, detail) values (auth.uid(), '首次账号成为管理员', '');
    return true;
  end if;
  return false;
end;
$$;

create or replace function public.submit_application(p_application_id uuid, p_note text default '')
returns void language plpgsql security definer set search_path = public, private, pg_temp as $$
declare a public.applications%rowtype; threshold_value numeric(12,2); next_version integer;
begin
  select * into a from public.applications where id = p_application_id for update;
  if a.id is null or a.owner_id <> auth.uid() or a.status not in ('draft','changes_requested') then raise exception '当前申请不能提交'; end if;
  select threshold into threshold_value from public.settings where id = 1;
  next_version := a.version + 1;
  update public.applications set status = 'finance_pending', version = next_version, rule_threshold = threshold_value, updated_at = now() where id = a.id;
  insert into public.approval_actions(application_id, version, actor_id, action, note) values (a.id, next_version, auth.uid(), '提交申请', coalesce(p_note, ''));
  insert into public.audit_logs(actor_id, event, detail) values (auth.uid(), '提交申请', a.id::text);
end;
$$;

create or replace function private.review_application(p_application_id uuid, p_decision text, p_note text)
returns void language plpgsql security definer set search_path = public, private, pg_temp as $$
declare a public.applications%rowtype; next_status text; reviewer_role text;
begin
  if length(coalesce(p_note, '')) = 0 then raise exception '请填写处理意见'; end if;
  select * into a from public.applications where id = p_application_id for update;
  if a.id is null or a.owner_id = auth.uid() then raise exception '不能处理此申请'; end if;
  reviewer_role := case when a.status = 'finance_pending' then 'finance' when a.status = 'chair_pending' then 'chair' else null end;
  if reviewer_role is null or not private.has_role(auth.uid(), reviewer_role) then raise exception '没有对应处理权限'; end if;
  if p_decision = 'approve' then
    next_status := case when reviewer_role = 'finance' and a.amount >= a.rule_threshold then 'chair_pending' else 'payment_info_required' end;
  elsif p_decision = 'return' then next_status := 'changes_requested';
  elsif p_decision = 'reject' then next_status := 'rejected';
  else raise exception '未知处理方式';
  end if;
  update public.applications set status = next_status, updated_at = now() where id = a.id;
  insert into public.approval_actions(application_id, version, actor_id, action, note) values (a.id, a.version, auth.uid(), case p_decision when 'approve' then '审批通过' when 'return' then '退回修改' else '拒绝申请' end, p_note);
  insert into public.audit_logs(actor_id, event, detail) values (auth.uid(), '处理申请', a.id::text || ':' || p_decision);
end;
$$;

create or replace function public.approve_application(p_application_id uuid, p_note text) returns void language sql security definer set search_path = public, private, pg_temp as $$ select private.review_application(p_application_id, 'approve', p_note); $$;
create or replace function public.return_application(p_application_id uuid, p_note text) returns void language sql security definer set search_path = public, private, pg_temp as $$ select private.review_application(p_application_id, 'return', p_note); $$;
create or replace function public.reject_application(p_application_id uuid, p_note text) returns void language sql security definer set search_path = public, private, pg_temp as $$ select private.review_application(p_application_id, 'reject', p_note); $$;

create or replace function public.cancel_application(p_application_id uuid, p_note text default '')
returns void language plpgsql security definer set search_path = public, private, pg_temp as $$
declare a public.applications%rowtype;
begin
  select * into a from public.applications where id = p_application_id for update;
  if a.id is null or a.owner_id <> auth.uid() or a.status not in ('draft','changes_requested','finance_pending','chair_pending') then raise exception '当前申请不能撤回'; end if;
  update public.applications set status = 'cancelled', updated_at = now() where id = a.id;
  insert into public.approval_actions(application_id, version, actor_id, action, note) values (a.id, a.version, auth.uid(), '撤回申请', p_note);
end;
$$;

create or replace function public.add_application_file(p_application_id uuid, p_kind text, p_storage_path text, p_name text, p_mime text)
returns uuid language plpgsql security definer set search_path = public, private, pg_temp as $$
declare a public.applications%rowtype; file_id uuid;
begin
  select * into a from public.applications where id = p_application_id;
  if a.id is null or a.owner_id <> auth.uid() or a.status not in ('draft','changes_requested') or p_kind <> 'attachment' then raise exception '当前不能添加附件'; end if;
  insert into public.application_files(application_id, owner_id, kind, storage_path, name, mime) values (a.id, a.owner_id, p_kind, p_storage_path, left(p_name, 180), p_mime) returning id into file_id;
  return file_id;
end;
$$;

create or replace function public.submit_payment_info(p_application_id uuid, p_recipient text, p_storage_path text, p_name text, p_mime text)
returns void language plpgsql security definer set search_path = public, private, pg_temp as $$
declare a public.applications%rowtype;
begin
  select * into a from public.applications where id = p_application_id for update;
  if a.id is null or a.owner_id <> auth.uid() or a.status <> 'payment_info_required' or length(trim(p_recipient)) = 0 then raise exception '当前不能提交收款信息'; end if;
  insert into public.application_files(application_id, owner_id, kind, storage_path, name, mime) values (a.id, a.owner_id, 'qr', p_storage_path, left(p_name, 180), p_mime);
  update public.applications set recipient = left(trim(p_recipient), 80), status = 'payment_pending', updated_at = now() where id = a.id;
  insert into public.approval_actions(application_id, version, actor_id, action, note) values (a.id, a.version, auth.uid(), '提交收款信息', trim(p_recipient));
end;
$$;

create or replace function public.record_payment(p_application_id uuid, p_reference text, p_storage_path text, p_name text, p_mime text)
returns void language plpgsql security definer set search_path = public, private, pg_temp as $$
declare a public.applications%rowtype;
begin
  select * into a from public.applications where id = p_application_id for update;
  if a.id is null or a.owner_id = auth.uid() or a.status <> 'payment_pending' or (not private.has_role(auth.uid(), 'cashier') and not private.has_role(auth.uid(), 'admin')) then raise exception '当前不能登记付款'; end if;
  insert into public.payments(application_id, amount, reference, actor_id) values (a.id, a.amount, left(trim(p_reference), 120), auth.uid());
  insert into public.application_files(application_id, owner_id, kind, storage_path, name, mime) values (a.id, a.owner_id, 'receipt', p_storage_path, left(p_name, 180), p_mime);
  update public.applications set status = 'paid', updated_at = now() where id = a.id;
  insert into public.approval_actions(application_id, version, actor_id, action, note) values (a.id, a.version, auth.uid(), '登记人工付款', trim(p_reference));
end;
$$;

create or replace function public.update_approval_threshold(p_threshold numeric)
returns void language plpgsql security definer set search_path = public, private, pg_temp as $$
begin
  if not private.has_role(auth.uid(), 'admin') or p_threshold <= 0 or p_threshold > 10000000 then raise exception '没有权限或金额无效'; end if;
  update public.settings set threshold = round(p_threshold, 2), updated_at = now(), updated_by = auth.uid() where id = 1;
  insert into public.audit_logs(actor_id, event, detail) values (auth.uid(), '更新审批门槛', round(p_threshold, 2)::text);
end;
$$;

create or replace function public.set_member_roles(p_user_id uuid, p_roles text[], p_active boolean)
returns void language plpgsql security definer set search_path = public, private, pg_temp as $$
begin
  if not private.has_role(auth.uid(), 'admin') or p_user_id = auth.uid() or exists(select 1 from unnest(p_roles) r where r not in ('finance','chair','cashier','admin')) then raise exception '没有权限或角色无效'; end if;
  update public.profiles set active = p_active where id = p_user_id;
  delete from public.user_roles where user_id = p_user_id;
  insert into public.user_roles(user_id, role) select p_user_id, r from unnest(p_roles) r;
  insert into public.audit_logs(actor_id, event, detail) values (auth.uid(), '更新成员权限', p_user_id::text);
end;
$$;


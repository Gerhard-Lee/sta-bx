create extension if not exists pgcrypto;
create schema if not exists private;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null default '',
  email text not null default '',
  department text not null default '',
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.user_roles (
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null check (role in ('finance','chair','cashier','admin')),
  primary key (user_id, role)
);

create table if not exists public.settings (
  id integer primary key check (id = 1),
  threshold numeric(12,2) not null default 100.00 check (threshold > 0),
  updated_at timestamptz not null default now(),
  updated_by uuid references public.profiles(id)
);

create table if not exists public.applications (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references public.profiles(id),
  title text not null check (char_length(title) between 1 and 120),
  purpose text not null check (char_length(purpose) between 1 and 5000),
  amount numeric(12,2) not null check (amount > 0 and amount <= 10000000),
  category text not null check (char_length(category) between 1 and 80),
  department text not null check (char_length(department) between 1 and 80),
  use_date date not null,
  status text not null default 'draft' check (status in ('draft','finance_pending','chair_pending','changes_requested','rejected','payment_info_required','payment_pending','paid','cancelled')),
  version integer not null default 0 check (version >= 0),
  rule_threshold numeric(12,2),
  recipient text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.application_files (
  id uuid primary key default gen_random_uuid(),
  application_id uuid not null references public.applications(id) on delete cascade,
  owner_id uuid not null references public.profiles(id),
  kind text not null check (kind in ('attachment','qr','receipt')),
  storage_path text not null unique,
  name text not null,
  mime text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.approval_actions (
  id bigint generated by default as identity primary key,
  application_id uuid not null references public.applications(id) on delete cascade,
  version integer not null,
  actor_id uuid not null references public.profiles(id),
  action text not null,
  note text not null default '',
  created_at timestamptz not null default now()
);

create table if not exists public.payments (
  application_id uuid primary key references public.applications(id) on delete cascade,
  amount numeric(12,2) not null,
  reference text not null unique,
  actor_id uuid not null references public.profiles(id),
  created_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references public.profiles(id),
  event text not null,
  detail text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists applications_owner_updated_idx on public.applications(owner_id, updated_at desc);
create index if not exists applications_status_updated_idx on public.applications(status, updated_at desc);
create index if not exists approval_actions_application_idx on public.approval_actions(application_id, id desc);
create index if not exists application_files_application_idx on public.application_files(application_id, created_at);


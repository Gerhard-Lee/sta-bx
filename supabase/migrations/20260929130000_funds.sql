create or replace function private.has_role(p_user_id uuid, p_role text)
returns boolean language sql stable security definer set search_path = public, private, pg_temp as $$
  select p_user_id is not null and exists(select 1 from public.user_roles where user_id = p_user_id and role = p_role);
$$;
create or replace function private.has_any_role(p_user_id uuid)
returns boolean language sql stable security definer set search_path = public, private, pg_temp as $$
  select p_user_id is not null and exists(select 1 from public.user_roles where user_id = p_user_id);
$$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = public, pg_temp as $$
begin
  insert into public.profiles(id, full_name, email)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)), coalesce(new.email, ''))
  on conflict (id) do nothing;
  return new;
end;
$$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users for each row execute procedure public.handle_new_user();


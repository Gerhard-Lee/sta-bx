create or replace function public.app_bind_email(p_actor_id uuid, p_user_id uuid, p_email text)
returns void language plpgsql security definer set search_path = public, private, pg_temp as $$
declare normalized text := lower(trim(coalesce(p_email, '')));
begin
  if p_actor_id is null or p_user_id is null or p_actor_id <> p_user_id then raise exception '只能绑定自己的邮箱'; end if;
  if char_length(normalized) > 254 then raise exception '邮箱地址过长'; end if;
  if normalized <> '' and normalized !~* '^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$' then raise exception '邮箱格式不正确'; end if;
  update public.app_users set email = nullif(normalized, ''), updated_at = now() where id = p_user_id and active;
  if not found then raise exception '账号不存在或已停用'; end if;
  insert into public.audit_logs(actor_id, event, detail)
  values (p_user_id, '绑定邮箱', case when normalized = '' then '清除邮箱' else '邮箱已更新' end);
end $$;


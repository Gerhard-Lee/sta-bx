  end loop;
end $$;
create or replace function public.app_admin_create_user(p_actor_id uuid, p_username text, p_password text, p_full_name text, p_department text, p_roles text[], p_email text default '')
returns jsonb language plpgsql security definer set search_path = public, private, pg_temp as $$
declare u jsonb; normalized text := lower(trim(coalesce(p_email, '')));
begin
  if not private.app_user_has_role(p_actor_id, 'admin') then raise exception '没有管理员权限'; end if;
  if exists(select 1 from unnest(coalesce(p_roles, '{}'::text[])) r where r is null or r not in ('finance','chair','admin')) then raise exception '角色无效'; end if;
  if char_length(normalized) > 254 or (normalized <> '' and normalized !~* '^[a-z0-9._%+-]+@[a-z0-9.-]+\.[a-z]{2,}$') then raise exception '邮箱格式不正确'; end if;
  u := private.app_insert_user(p_username, p_password, p_full_name, p_department);
  if normalized <> '' then update public.app_users set email = normalized, updated_at = now() where id = (u->>'id')::uuid; end if;
  perform public.app_set_member_roles(p_actor_id, (u->>'id')::uuid, p_roles, true);
  insert into public.audit_logs(actor_id, event, detail, metadata)
  values (p_actor_id, '添加用户', '创建 @' || (u->>'username') || '（' || (u->>'full_name') || '）',
    jsonb_build_object('target_user_id', u->>'id', 'target_username', u->>'username', 'roles', p_roles, 'email_bound', normalized <> ''));
  return u;
end $$;


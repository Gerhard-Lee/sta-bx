create or replace function public.app_update_email_notify(p_actor_id uuid, p_enabled boolean, p_events text[])
returns void language plpgsql security definer set search_path = public, private, pg_temp as $$
declare old_value boolean; old_events text[]; normalized text[];
begin
  if not private.app_user_has_role(p_actor_id, 'admin') or p_enabled is null then raise exception '没有管理员权限或参数无效'; end if;
  if p_events is null or exists(
       select 1 from unnest(p_events) e
       where e is null or e not in ('待财委审批','待主席审批','退回修改','待补充收款码','待付款登记','拒绝申请','已付款')) then
    raise exception '提醒类型无效';
  end if;
  select coalesce(array_agg(e order by ord), '{}'::text[]) into normalized
  from unnest(array['待财委审批','待主席审批','退回修改','待补充收款码','待付款登记','拒绝申请','已付款']) with ordinality as t(e, ord)
  where e = any(p_events);
  select email_notify_enabled, email_notify_events into old_value, old_events from public.settings where id = 1 for update;
  update public.settings
     set email_notify_enabled = p_enabled, email_notify_events = normalized, updated_at = now(), updated_by = p_actor_id
   where id = 1;
  insert into public.audit_logs(actor_id, event, detail, metadata)
  values (p_actor_id, '修改邮件通知设置',
    left(case when p_enabled then '开启邮件通知' else '关闭邮件通知' end || '：' ||
      case when cardinality(normalized) = 0 then '未勾选任何提醒类型' else array_to_string(normalized, '、') end, 200),
    jsonb_build_object(
      '总开关', jsonb_build_object('原值', old_value, '新值', p_enabled),
      '提醒类型', jsonb_build_object('原值', to_jsonb(old_events), '新值', to_jsonb(normalized))));
end $$;


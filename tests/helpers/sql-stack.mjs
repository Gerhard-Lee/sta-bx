//   4) 其余迁移：20261004210000_email_notify.sql 开头的 fail-fast 明确要求散装 SQL 先执行。
//   5) 全部同名 .verify.sql（各自包在 begin; … rollback; 里，不留下验证数据）。
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import path from 'node:path';
import { PGlite } from '@electric-sql/pglite';
import { pgcrypto } from '@electric-sql/pglite/contrib/pgcrypto';

export const SQL_STACK_TIMEOUT = 120000;

const ROOT = import.meta.dirname ? path.resolve(import.meta.dirname, '..', '..') : process.cwd();
const SQL_ROOT = path.join(ROOT, 'supabase');
export const fromRoot = (absolute) => path.relative(ROOT, absolute).split(path.sep).join('/');
export const readSql = (absolute) => readFileSync(absolute, 'utf8');
export const rootPath = (...parts) => path.join(ROOT, ...parts);

// 真实的 Supabase 里 auth/storage schema 与 anon/authenticated/service_role 角色由平台提供，
// PGlite 里没有。这里只建"让迁移里的建表、建策略、授权语句能解析"的最小占位，不模拟任何 Supabase 行为。
const PLATFORM_PLACEHOLDER = `
do $$
begin
  if not exists(select 1 from pg_roles where rolname = 'anon') then create role anon nologin; end if;
  if not exists(select 1 from pg_roles where rolname = 'authenticated') then create role authenticated nologin; end if;
  if not exists(select 1 from pg_roles where rolname = 'service_role') then create role service_role nologin; end if;
end $$;

create schema if not exists auth;
create schema if not exists storage;

-- 迁移里的 on_auth_user_created 触发器与 handle_new_user() 用到 id/email/raw_user_meta_data。
create table if not exists auth.users (
  id uuid primary key default gen_random_uuid(),
  email text,
  raw_user_meta_data jsonb not null default '{}'::jsonb
);
-- 20260929130000_funds.sql 的旧 RLS 策略直接调用 auth.uid()；这里只要能被解析。
create or replace function auth.uid() returns uuid language sql stable as $$ select null::uuid $$;

-- 20260929130000_funds.sql 会往 storage.buckets 插 bucket，并在 storage.objects 上建策略与 revoke。
create table if not exists storage.buckets (
  id text primary key,
  name text not null,
  public boolean not null default false,
  file_size_limit bigint,
  allowed_mime_types text[]
);
create table if not exists storage.objects (
  id uuid primary key default gen_random_uuid(),
  bucket_id text references storage.buckets(id),
  name text,
  owner uuid,
  created_at timestamptz not null default now()
);
alter table storage.objects enable row level security;

-- cron 桩：只提供 pg_cron 的 cron.job 表与 schedule/unschedule 两个函数。
-- 真实的 pg_cron 在 PGlite 里装不上（pg_available_extensions 里没有它，迁移会走"跳过"分支），
-- 但有了这个桩，email_notify_cron.verify.sql 就能直接调 private.app_schedule_email_cron，
-- 真正验证任务名/周期/x-app-cron 头/pg_net 超时写对了——否则那几条断言永远不会执行。
create schema if not exists cron;
create table if not exists cron.job (
  jobid bigint generated by default as identity primary key,
  jobname text,
  schedule text,
  command text,
  active boolean not null default true
);
create or replace function cron.schedule(job_name text, schedule text, command text) returns bigint
  language plpgsql as $$
  declare new_id bigint;
  begin
    insert into cron.job(jobname, schedule, command) values (job_name, schedule, command) returning jobid into new_id;
    return new_id;
  end $$;
create or replace function cron.unschedule(job_id bigint) returns boolean
  language plpgsql as $$
  begin
    delete from cron.job where jobid = job_id;
    return found;
  end $$;
`;

// supabase/migrations 下按 14 位时间戳升序的全部迁移（不含 .verify.sql）。

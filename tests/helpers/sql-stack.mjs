// 最终执行顺序：基线段 → 4 份散装 SQL → 内置 admin → 其余迁移 → 全部 verify（每个文件只执行一次）。
export const EXECUTION_ORDER = [...BASELINE_MIGRATIONS, ...BULK_FILES, ...LATE_MIGRATIONS, ...VERIFY_FILES];

function failure(file, error) {
  const lines = [`执行 ${fromRoot(file)} 失败`, `原始报错：${error.message}`];
  if (error.position) lines.push(`位置：${error.position}`);
  if (error.detail) lines.push(`detail：${error.detail}`);
  if (error.hint) lines.push(`hint：${error.hint}`);
  if (error.where) lines.push(`where：${error.where}`);
  const wrapped = new Error(lines.join('\n'));
  wrapped.cause = error;
  return wrapped;
}

/**
 * 建一个内存 PGlite 实例并把整套 SQL 栈执行一遍。
 * 返回 { db, executed, migrationFiles, bulkFiles, verifyFiles }；失败时关掉实例并抛出带文件名的错误。
 */
export async function createSqlStack() {
  const db = new PGlite({ extensions: { pgcrypto } });
  db.waitReady.catch(() => {});
  const executed = [];
  const runFile = async (file) => {
    const startedAt = Date.now();
    try {
      await db.exec(readSql(file));
    } catch (error) {
      throw failure(file, error);
    }
    executed.push({ file: fromRoot(file), ms: Date.now() - startedAt });
  };
  try {
    await db.exec(PLATFORM_PLACEHOLDER);
    for (const file of BASELINE_MIGRATIONS) await runFile(file);
    await runFile(BULK_FILES[0]);
    await db.exec(ADMIN_FIXTURE);
    for (const file of BULK_FILES.slice(1)) await runFile(file);
    for (const file of LATE_MIGRATIONS) await runFile(file);
    for (const file of VERIFY_FILES) await runFile(file);
  } catch (error) {
    // 起不来的实例留着只会拖住事件循环。
    await db.close().catch(() => {});
    throw error;
  }
  return {
    db,
    executed,
    migrationFiles: MIGRATION_FILES.map(fromRoot),
    bulkFiles: BULK_FILES.map(fromRoot),
    verifyFiles: VERIFY_FILES.map(fromRoot),
  };
}
